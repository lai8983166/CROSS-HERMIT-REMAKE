"""Bounded per-case source witnesses; no duplicate historical frame snapshots.

One original initial image, actual native boundary bytes and original code
reconstruct every transaction. The fixed accepted parent is a provenance
dependency; its multi-GiB case tree is neither parsed nor copied into this one.
"""
import argparse
import gc
import hashlib
import json
from pathlib import Path
import sys
import time
import traceback
from datetime import datetime,timezone,timedelta

from tools import terminal_unit_frontends_emulation as source
from tools import terminal_unit_frontends_delta as delta

ROOT=source.ROOT
PARENT='analysis/terminal-battle-exit-prefix-acceptance-v1-20261102.json'
PARENT_SHA='c4471be997485202327f99be3ad22655b5f9da5968b88d1e214377f1edaae106'
# Leave16MiB inside the total256MiB target for small reports/build witnesses.
PER_CASE_LIMIT=60*1024*1024


def identity(path):
    path=Path(path)
    h=hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda:f.read(1048576),b''):h.update(block)
    return dict(path=path.relative_to(ROOT).as_posix(),bytes=path.stat().st_size,sha256=h.hexdigest())


def fixed_base():
    raw=(ROOT/PARENT).read_bytes()
    if hashlib.sha256(raw).hexdigest()!=PARENT_SHA:raise ValueError('fixed accepted predecessor changed')
    parent=json.loads(raw)
    source_identity=parent['source_report']
    if (ROOT/source_identity['path']).stat().st_size!=source_identity['bytes']:
        raise ValueError('retained parent source5 missing or wrong extent')
    original=identity(source.previous.overlay.SOURCE)
    if original['sha256']!='588b4288e4c737dc489d2b9bc0652cca85e3d668b1784942ef4b4bda916f1005':
        raise ValueError('original executable changed')
    base_identity=dict(parent_acceptance=identity(ROOT/PARENT),accepted_source5=source_identity,
                       original_executable=original,
                       parent_source5_freshly_rehashed=False,
                       parent_source5_not_used_as_guest_state=True)
    # Original byte chunks are addressed by this authenticated local input.
    # No historical memory snapshot or native handle is restored.
    base=dict(original_image_hex=source.previous.CODE.hex(),parent_acceptance=parent)
    return base_identity,base


def implementation_files():
    paths=set()
    for module in list(sys.modules.values()):
        name=getattr(module,'__file__',None)
        if name:
            path=Path(name).resolve()
            if path.suffix=='.py' and path.is_relative_to(ROOT/'tools'):paths.add(path)
    return {p.relative_to(ROOT).as_posix():identity(p) for p in sorted(paths)}


def compact_case(row):
    # Native payloads and original input/complete forward RAM are evidence.
    # Old observers' repeated full snapshots can be regenerated by replay and
    # carry no additional native input, so they are not separately persisted.
    keep=('input','combat_input','unit_frontends','CRT_trace','GPU_trace','GDI_trace',
          'CRT_cleanup','GPU_cleanup','CRT_exit','GPU_exit','typed_GPU_projection',
          'last_dialogue_GDI_lifetimes','platform','pending_CPU',
          'APIs','task_APIs','IME_identity',
          'instructions','writes','code_trace_sha256','write_trace_sha256')
    result={key:row[key] for key in keep}
    result.update(schema_version=1,source_execution_complete=True,accepted=False,
                  frontier=row['terminal_battle_exit_prefix']['freeze'],
                  forward_memory=row['final'],forward_CPU=row['pending_CPU'],
                  reconstructed_by_original_instructions=True,
                  legacy_repeated_frame_memory_retained=False)
    return result


def produce(prefix,index,scene_failure_checkpoint=False):
    prefix=Path(prefix)
    process_path=Path(str(prefix)+'.process.json')
    if process_path.exists():raise ValueError('fresh immutable source process report required')
    base_identity,base=fixed_base()
    helper_name=prefix.name+'-'+str(index)
    ch,gh,build=source.images.CORE_helpers(helper_name)
    case=source.previous.overlay.parent.corpus()[index]
    process=dict(schema_version=1,accepted=False,case=case,fixed_base=base_identity,
                 helper_build=build,implementation_start=implementation_files(),
                 source_execution_complete=False,ordinary_large_Git_object=False)
    process['started_at']=datetime.now(timezone(timedelta(hours=8))).isoformat()
    start=time.monotonic();writer=None

    def save_failed_scene(machine):
        # One bounded guest-only state for local tail diagnosis. Reusing the
        # opaque native identities in a new native owner is never valid.
        checkpoint = delta.CorpusWriter(Path(str(prefix)+'-failed-scene'), base_identity,
                                        budget=PER_CASE_LIMIT)
        try:
            checkpoint.append(case['name'], dict(development_only=True, accepted=False,
                original_native_lifetime_resumable=False, CPU=machine.cpu(),
                regions=[list(r) for r in machine.uc.mem_regions()],
                mutable=[list(r) for r in machine.mutable], memory=machine.snapshot()), base)
            checkpoint.close()
            process['development_checkpoint'] = [identity(path) for path in checkpoint.paths]
        except Exception:
            checkpoint.abort()
            raise

    try:
        row=source.run_case(case,ch,gh,scene_failure=save_failed_scene if scene_failure_checkpoint else None)
        witness=compact_case(row)
        del row;gc.collect()
        writer=delta.CorpusWriter(prefix,base_identity,budget=PER_CASE_LIMIT)
        writer.append(case['name'],witness,base)
        writer.close()
        process.update(source_execution_complete=True,artifacts=[identity(p) for p in writer.paths],
                       current_primary_bytes=sum(p.stat().st_size for p in writer.paths),
                       full_source_and_one_copy_total_limit=2*delta.PRIMARY_LIMIT,
                       frontier={k:v for k,v in witness['frontier'].items() if k!='stack_hex'},
                       final_trace=witness['unit_frontends']['execution']['final_trace'])
    except Exception as error:
        if writer is not None:writer.abort()
        process.update(error=repr(error),context=getattr(error,'unit_frontends_context',None),
                       traceback=traceback.format_exc(limit=12))
        raise
    finally:
        process.update(implementation_end=implementation_files(),duration_seconds=round(time.monotonic()-start,2))
        process['implementation_unchanged']=all(process['implementation_end'].get(k)==v
                                               for k,v in process['implementation_start'].items())
        with process_path.open('x',encoding='utf8',newline='\n') as f:
            json.dump(process,f,separators=(',',':'));f.write('\n')
    if not process['implementation_unchanged']:raise ValueError('loaded source implementations changed during run')
    return process


def read_case(prefix,index):
    prefix=Path(prefix)
    base_identity,base=fixed_base()
    case=source.previous.overlay.parent.corpus()[index]
    stream=delta.read_corpus(str(prefix)+'.delta.jsonl.gz',str(prefix)+'.chunks.zip',
                             base_identity,[(case['name'],base)])
    result=None
    for name,row in stream:
        if result is not None:raise ValueError('one fixed source case per witness')
        result=row
    if result is None:raise ValueError('missing complete fixed source witness')
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',required=True)
    parser.add_argument('--case',type=int,choices=(0,1),required=True)
    parser.add_argument('--scene-failure-checkpoint',action='store_true',
                        help='retain one bounded guest-only checkpoint on an original scene failure')
    args=parser.parse_args()
    print(json.dumps(produce(ROOT/args.out,args.case,args.scene_failure_checkpoint),ensure_ascii=False),flush=True)
